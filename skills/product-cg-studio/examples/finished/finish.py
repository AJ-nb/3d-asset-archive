"""Adapt the sample blockout into the silver-aluminium concept and preserve editable details."""
import math
from pathlib import Path

import bpy
from mathutils import Vector


if not bpy.data.filepath:
    raise ValueError("Open the blockout generated by examples/make_demo.py first")
folder = Path(bpy.data.filepath).resolve().parent
outputs = (folder / "stage-01-clay.png", folder / "volume-controller.blend")
if any(path.exists() for path in outputs):
    raise FileExistsError("Run from a fresh blockout directory; a target already exists")
scene = bpy.context.scene
scene.cycles.samples = 24
scene.cycles.use_denoising = True
scene.unit_settings.system = "METRIC"
scene.unit_settings.scale_length = 0.04
scene.unit_settings.length_unit = "MILLIMETERS"
scene.render.image_settings.color_mode = "RGB"
scene.render.threads_mode = "FIXED"
scene.render.threads = 10
scene.render.resolution_x = 1280
scene.render.resolution_y = 640
scene.render.resolution_percentage = 100
bpy.context.preferences.filepaths.save_version = 0


def paint(name, colour, metal, rough):
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = (*colour, 1)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = (*colour, 1)
    bsdf.inputs["Metallic"].default_value = metal
    bsdf.inputs["Roughness"].default_value = rough
    return mat


def assign(o, mat):
    o.data.materials.clear()
    o.data.materials.append(mat)


def bevel(o, width):
    mod = o.modifiers.new("Edge break", "BEVEL")
    mod.width = width
    mod.segments = 3
    o.modifiers.new("Weighted normals", "WEIGHTED_NORMAL")


def chip(name, xy, size, height, z, material, rotation=0):
    bpy.ops.mesh.primitive_cube_add(size=1, location=(*xy, z))
    obj = bpy.context.object
    obj.name = name
    obj.dimensions = (*size, height)
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    obj.rotation_euler.z = rotation
    assign(obj, material)
    bevel(obj, min(height / 3, min(size) / 3))
    return obj


def aim(o, pt):
    o.rotation_euler = (Vector(pt) - o.location).to_track_quat("-Z", "Y").to_euler()


objects = bpy.data.objects
hero, detail = objects["Hero"], objects["Detail"]
hero.location = (2.15, -5.4, 3.48)
hero.data.ortho_scale = 5.65
aim(hero, (-0.23, -0.03, 0.28))
detail.location = (-2.85, -3.48, 4.8)
detail.data.ortho_scale = 2.68
aim(detail, (-0.56, 0.01, 0.48))
scene.camera = hero

clay = paint("QA | neutral clay", (0.50, 0.50, 0.50), 0.0, 0.68)
view_layer = scene.view_layers[0]
view_layer.material_override = clay
scene.render.resolution_percentage = 30
scene.cycles.samples = 3
scene.render.filepath = str(folder / "stage-01-clay.png")
bpy.ops.render.render(write_still=True)
view_layer.material_override = None

silver = paint("01 | natural machined aluminium - knob sides", (0.74, 0.78, 0.80), 0.98, 0.245)
face = paint("02 | concentric turned aluminium - cap", (0.72, 0.76, 0.80), 0.98, 0.31)
graphite = paint("03 | graphite powder coat - shell", (0.028, 0.039, 0.047), 0.28, 0.47)
keymat = paint("04 | charcoal matte - keys", (0.057, 0.069, 0.078), 0.12, 0.44)
trim = paint("05 | black elastomer", (0.012, 0.014, 0.016), 0.05, 0.65)
mark = paint("06 | grey-white infill", (0.70, 0.76, 0.75), 0.12, 0.37)
orange = paint("07 | vermilion inlay", (0.90, 0.093, 0.021), 0.08, 0.39)
tablemat = paint("08 | studio sweep", (0.26, 0.32, 0.32), 0.00, 0.88)
for name, mat in [("Foot", trim), ("Bearing ring", trim), ("Enclosure", graphite), ("Table", tablemat)]:
    assign(objects[name], mat)

# Eight stations define a lathed rim with shallow axial grip flutes.
knob = objects["Dial"]
knob.animation_data_clear()
knob.rotation_euler.z = math.radians(-37)
n = 480
stations = [(0.484, -0.12, 0), (0.515, -0.108, 0), (0.527, -0.09, 0.012),
            (0.528, -0.072, 0.019), (0.528, 0.069, 0.019), (0.527, 0.087, 0.012),
            (0.520, 0.102, 0), (0.504, 0.120, 0), (0.489, 0.120, 0),
            (0.486, 0.117, 0), (0.480, 0.117, 0), (0.476, 0.120, 0)]
vertices = []
for radius, z, flute in stations:
    for i in range(n):
        a = math.tau * i / n
        r = radius - flute * (0.5 + 0.5 * math.cos(60 * a)) ** 2
        vertices.append((r * math.cos(a), r * math.sin(a), z))
faces = []
for j in range(len(stations) - 1):
    for i in range(n):
        p = j * n + i
        q = j * n + (i + 1) % n
        faces.append((p, q, q + n, p + n))
faces.append(tuple(reversed(range(n))))
faces.append(tuple(range(n * (len(stations) - 1), n * len(stations))))
mesh = bpy.data.meshes.new("Turned blank | 60 grip flutes")
mesh.from_pydata(vertices, [], faces)
mesh.update()
knob.data = mesh
knob.modifiers.clear()
knob.data.materials.append(silver)
knob.data.materials.append(face)
for poly in mesh.polygons[:-2]:
    poly.use_smooth = True
mesh.polygons[-1].material_index = 1
# Radial turning mapped around the local spindle axis, independent of camera.
nodes, links = face.node_tree.nodes, face.node_tree.links
coords = nodes.new("ShaderNodeTexCoord")
wave = nodes.new("ShaderNodeTexWave")
wave.wave_type = "RINGS"
wave.rings_direction = "Z"
wave.inputs["Scale"].default_value = 27
links.new(coords.outputs["Object"], wave.inputs["Vector"])
bump = nodes.new("ShaderNodeBump")
bump.inputs["Strength"].default_value = 0.16
bump.inputs["Distance"].default_value = 0.0009
links.new(wave.outputs["Fac"], bump.inputs["Height"])
links.new(bump.outputs["Normal"], nodes.get("Principled BSDF").inputs["Normal"])
rough = nodes.new("ShaderNodeMapRange")
rough.inputs["To Min"].default_value = 0.245
rough.inputs["To Max"].default_value = 0.355
links.new(wave.outputs["Fac"], rough.inputs["Value"])
links.new(rough.outputs["Result"], nodes.get("Principled BSDF").inputs["Roughness"])
tick = objects["Dial index"]
assign(tick, orange)
tick.location.y = 0.365

for i in range(17):
    a = math.radians(-133 + i * 16.5)
    xy = (-0.64 + 0.674 * math.sin(a), 0.674 * math.cos(a))
    chip(f"Scale {i + 1:02d}", xy, (0.013, 0.074 if i % 4 == 0 else 0.039), 0.003, 0.442, mark, -a)

for row, y in enumerate((-0.33, 0.0, 0.33)):
    assign(objects[f"Key {row + 1}"], keymat)
    # Compact geometric plus, mute and minus function marks.
    if row == 0 or row == 2:
        chip(f"{row} | bar", (0.72, y), (0.096, 0.017), 0.003, 0.518, mark)
        if row == 2:
            chip("Plus | upright", (0.72, y), (0.017, 0.096), 0.003, 0.519, mark)
    else:
        for i, h in enumerate((0.030, 0.070, 0.101, 0.049)):
            chip(f"Mute | level {i}", (0.685 + i * 0.024, y), (0.013, h), 0.003, 0.518, mark)

world = scene.world or bpy.data.worlds.new("Studio environment")
scene.world = world
world.use_nodes = True
world.node_tree.nodes["Background"].inputs["Color"].default_value = (0.36, 0.39, 0.41, 1)
world.node_tree.nodes["Background"].inputs["Strength"].default_value = 0.48
for light in (o for o in scene.objects if o.type == "LIGHT"):
    light.data.color = {"Left softbox":(1.0, 0.925, 0.855), "Right fill":(0.84, 0.92, 1.0), "Rear strip":(1, 1, 1)}[light.name]
